import { describe, expect, it, mock } from "bun:test";
import { createOTP } from "@better-auth/utils/otp";
import { symmetricEncrypt } from "better-auth/crypto";
import { env } from "../../../shared/env";
import type { Logger } from "../../../shared/logger";
import { NoOpInstrumentation } from "../../../shared/services/noop-instrumentation";
import { DrizzleRgpdRepository } from "../infrastructure/repositories/drizzle-rgpd.repository";

function selectReturning(rows: unknown[]) {
  const query = { toSQL: () => ({ sql: "select secret" }), execute: async () => rows };

  return { select: () => ({ from: () => ({ where: () => ({ limit: () => query }) }) }) } as never;
}

function repository() {
  return new DrizzleRgpdRepository(
    { error: () => {} } as unknown as Logger,
    new NoOpInstrumentation(),
  );
}

async function storedSecret(plain: string) {
  return symmetricEncrypt({ key: env.BETTER_AUTH_SECRET, data: plain });
}

describe("DrizzleRgpdRepository.verifyTotp", () => {
  it("accepts the current code of a secret generated by two-factor", async () => {
    const secret = "generated-two-factor-secret-0123456789";
    const code = await createOTP(secret, { period: 30, digits: 6 }).totp();

    const result = await repository().verifyTotp(
      "u1",
      code,
      selectReturning([{ secret: await storedSecret(secret) }]),
    );

    expect(result.getValue()).toBe(true);
  });

  it("accepts the current code of a base32 secret imported from another provider", async () => {
    const helloDeadBeef = new Uint8Array([
      0x48, 0x65, 0x6c, 0x6c, 0x6f, 0x21, 0xde, 0xad, 0xbe, 0xef,
    ]);
    const code = await createOTP(helloDeadBeef, { period: 30, digits: 6 }).totp();

    const result = await repository().verifyTotp(
      "u1",
      code,
      selectReturning([{ secret: await storedSecret("base32:jbswy3dpehpk3pxp") }]),
    );

    expect(result.getValue()).toBe(true);
  });

  it("rejects the code and reports the error when the stored secret cannot be decrypted", async () => {
    const capture = mock(() => undefined);
    const instrumentation = Object.assign(new NoOpInstrumentation(), { capture });
    const repo = new DrizzleRgpdRepository(
      { error: () => {} } as unknown as Logger,
      instrumentation,
    );

    const result = await repo.verifyTotp(
      "u1",
      "123456",
      selectReturning([{ secret: "not-an-encrypted-secret" }]),
    );

    expect(result.getValue()).toBe(false);
    expect(capture).toHaveBeenCalledTimes(1);
  });
});
